"""Draw BUOY's boot logo (a bell buoy ringing on a sine-wave sea) and pack it into a small RGB565 run-length
bitmap: assets/buoy-boot.png (the picture, 240 x 240) and firmware/gen/buoy_boot_logo.h (what the firmware draws)."""

import math
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
S = 4                                   # drawn 4x larger, then shrunk: smooth edges
BG = (10, 16, 22)                       # the firmware's C_BG
BELL = (239, 159, 39)                   # C_BELL: the bell, the engine, the pitch
SEA = (93, 202, 165)                    # C_SEA: the always-on oscillator
HULL = (236, 232, 222)                  # C_KEY


def mix(c, a):
    return tuple(round(BG[i] + (c[i] - BG[i]) * a) for i in range(3))


img = Image.new("RGB", (240 * S, 240 * S), BG)
d = ImageDraw.Draw(img)
cx, cy = 120, 70
for r, a in ((20, 0.9), (34, 0.55), (48, 0.25)):     # the rings the bell sends out
    d.ellipse([(cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S], outline=mix(BELL, a), width=2 * S)
d.ellipse([(cx - 7) * S, (cy - 7) * S, (cx + 7) * S, (cy + 7) * S], fill=BELL)        # the bell
d.line([108 * S, 124 * S, 115 * S, 80 * S], fill=HULL, width=3 * S)                    # the cage
d.line([132 * S, 124 * S, 125 * S, 80 * S], fill=HULL, width=3 * S)
d.polygon([(100 * S, 124 * S), (140 * S, 124 * S), (133 * S, 146 * S), (107 * S, 146 * S)], fill=HULL)


def wave(y, a, width, colour):
    pts = [((40 + x / 4) * S, (y - math.sin((x / 4) * 2 * math.pi / 40) * a) * S) for x in range(0, 160 * 4 + 1)]
    d.line(pts, fill=colour, width=width * S, joint="curve")


wave(150, 5, 3, SEA)                    # the sea, always moving
wave(162, 5, 2, mix(SEA, 0.5))
font = ImageFont.truetype(str(root / "assets/fonts/IBMPlexMono-Medium.ttf"), 22 * S)
text = "B U O Y"
w = d.textlength(text, font=font)
d.text(((240 * S - w) / 2, 172 * S), text, font=font, fill=HULL)
image = img.resize((240, 240), Image.LANCZOS)
image = image.quantize(colors=24, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
image.save(root / "assets/buoy-boot.png")
image.resize((480, 480), Image.NEAREST).save(root / "assets/logo.png")

background = Image.new("RGB", image.size, image.getpixel((0, 0)))
left, top, right, bottom = ImageChops.difference(image, background).getbbox()


def rgb565(pixel):
    red, green, blue = pixel
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


pixels = map(rgb565, image.crop((left, top, right, bottom)).getdata())
runs = []
for colour, group in groupby(pixels):
    n = sum(1 for _ in group)
    while n > 65535:
        runs.append((65535, colour))
        n -= 65535
    runs.append((n, colour))
lines = []
for start in range(0, len(runs), 6):
    lines.append("    " + ", ".join(f"{count}, 0x{colour:04x}" for count, colour in runs[start:start + 6]) + ",")
header = (
    "/* Generated by tools/gen_boot_logo.py (assets/buoy-boot.png). */\n"
    f"#define BOOT_LOGO_X {left}u\n"
    f"#define BOOT_LOGO_Y {top}u\n"
    f"#define BOOT_LOGO_WIDTH {right - left}u\n"
    f"#define BOOT_LOGO_HEIGHT {bottom - top}u\n"
    "static const uint16_t boot_logo_runs[] = {\n"
    + "\n".join(lines) + "\n};\n"
)
(root / "firmware/gen/buoy_boot_logo.h").write_text(header)
print(f"{len(runs)} runs, box {left},{top} {right - left}x{bottom - top}")
