"""BUOY's numbers, worked out once here (the FM-1 has no floating point) and written into
firmware/gen/buoy_tables.h: the sea's wavetables, pitch tables, the RING times, the LFO rates, the ENV times."""

import math
from pathlib import Path

root = Path(__file__).resolve().parent.parent
FS = 44100
out = ["/* Generated by tools/gen_tables.py: do not edit. */", "#pragma once", ""]


def table(ctype, name, values, per_line=12):
    out.append(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("};")


# --- the sea's waves: one cycle of 256 points each, band-limited (32 harmonics at most)
N = 256


def additive(weights):
    w = [0.0] * N
    for h, (amp, phase) in weights.items():
        for i in range(N):
            w[i] += amp * math.sin(2 * math.pi * h * i / N + phase)
    peak = max(abs(x) for x in w)
    return [round(x * 30000 / peak) for x in w]


def gauss(x, mu, sd):
    return math.exp(-0.5 * ((x - mu) / sd) ** 2)


waves = {
    "SINE": {1: (1, 0)},
    "TRIANGLE": {n: ((-1) ** ((n - 1) // 2) / n ** 2, 0) for n in range(1, 32, 2)},
    "SAW": {n: (1 / n, 0) for n in range(1, 33)},
    "SQUARE": {n: (1 / n, 0) for n in range(1, 32, 2)},
    "GLASS": {1: (1, 0), 2: (0.12, 0.4), 5: (0.45, 1.1), 9: (0.32, 2.0), 14: (0.18, 0.7), 20: (0.1, 2.6)},
    "REED": {n: ((1 / n ** 0.6) * (1 + 1.5 * gauss(n, 7, 2)), 0.3 * n) for n in range(1, 32, 2)},
    "VOICE": {n: ((1 / n ** 0.4) * (0.15 + gauss(n, 5.4, 1.2) + 0.7 * gauss(n, 9.2, 1.6) + 0.25 * gauss(n, 20, 3)),
                  0.5 * n) for n in range(1, 33)},
    "ORGAN": {1: (1, 0), 2: (0.8, 0), 3: (0.6, 0), 4: (0.5, 0), 6: (0.4, 0), 8: (0.3, 0)},
}
out.append("#define SEA_TABLES %d" % len(waves))
out.append("static const int16_t sea_tables[SEA_TABLES][256] = {")
for name, w in waves.items():
    vals = additive(w)
    out.append(f"    {{ /* {name} */")
    for i in range(0, N, 16):
        out.append("        " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    out.append("    },")
out.append("};")
out.append("")

# --- pitch: phase increments (2^32 = one cycle a sample) and periods (in 1/256 samples) of C9 .. B9 (MIDI 120..131)
inc = [round(440 * 2 ** ((120 + k - 69) / 12) * 2 ** 32 / FS) for k in range(12)]
table("uint32_t", "inc_c9", inc, 6)
period = [round(FS / (440 * 2 ** ((120 + k - 69) / 12)) * 256 * 64) for k in range(12)]   # x64: more precision
table("uint32_t", "period_c9_x64", period, 6)
# 2^(k/12) in Q16, k = 0..12
table("uint32_t", "semitone_q16", [round(65536 * 2 ** (k / 12)) for k in range(13)], 13)
out.append("")

# --- RING 0..100: how long a note sings after the sea stops feeding it, 60 ms .. 40 s (the time to fall 60 dB)
table("uint16_t", "ring_ms", [round(60 * (40000 / 60) ** (r / 100)) for r in range(101)], 12)
# --- LFO RATE: 64 steps, 0.01 Hz .. 20 Hz; the phase step a sample (2^32 = one cycle), and the rate in 1/100 Hz
rates = [0.01 * (2000) ** (i / 63) for i in range(64)]
table("uint32_t", "lfo_inc", [round(f * 2 ** 32 / FS) for f in rates], 8)
table("uint16_t", "lfo_hundredths", [round(f * 100) for f in rates], 16)
out.append("#define LFO_RATES 64u")
# --- ENV times, ms
env = [0, 5, 10, 20, 30, 50, 70, 100, 130, 160, 200, 250, 300, 400, 500, 600, 800, 1000, 1200, 1500, 1800, 2000,
       2500, 3000, 3500, 4000, 5000, 6000, 7000, 8000, 10000, 12000, 15000, 20000]
table("uint16_t", "env_ms", env, 12)
out.append(f"#define ENV_STEPS {len(env)}u")
out.append("")
(root / "firmware/gen/buoy_tables.h").write_text("\n".join(out) + "\n")
print("firmware/gen/buoy_tables.h written")
